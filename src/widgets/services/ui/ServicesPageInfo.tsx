interface ServicesPageInfoProps {
	category?: CategoryWithServices;
	service?: ServiceWithCategory;
}
export function ServicesPageInfo({ category, service }: ServicesPageInfoProps) {
	const data: CategoryWithServices | ServiceWithCategory | undefined = category ?? service;
	if (!data) return false;

	const bannerSrc = category
		? `/images/services/cards/${category.slug}.png`
		: `/images/services/cards/${service?.category.slug}.png`;

	return (
		<div className={`container ${styles.section}`}>
			<aside className={styles.aside}>
				<div>
					<h2>Наши услуги</h2>
					<span>{data.items.length}</span>
				</div>
			</aside>
			<main className={styles.main}>
				<BannerCategory
					title={data.title}
					description={data.description}
					imageSrc={bannerSrc}
				/>
				<section className="block-bottom">PRICE</section>
				<InfoBlock content={mockData.content} title={mockData.title} />
			</main>
		</div>
	);
}

interface BannerCategoryProps {
	title: string;
	description: string;
	imageSrc: string;
	className?: string;
}

function BannerCategory({ title, description, imageSrc, className }: BannerCategoryProps) {
	const { openModal } = useModal();

	return (
		<section className="block-bottom">
			<div className={styles.banner}>
				<div className={styles.img__wrap}>
					<Image
						src={imageSrc}
						alt=""
						className={styles.image}
						width={480}
						height={330}
					/>
				</div>
				<div className={styles.info}>
					<h1 className={`${styles.title} page-title`}>{title}</h1>
					{description && <p className={styles.description}>{description}</p>}

					<div className={styles.btns}>
						<Button variant="outline" onClick={() => openModal("common")}>
							Бесплатная консультация
						</Button>
						<Button onClick={() => openModal("common")}>Записаться на сервис</Button>
					</div>
				</div>
			</div>
		</section>
	);
}
